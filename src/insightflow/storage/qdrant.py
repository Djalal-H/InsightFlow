"""Qdrant vector-store adapter."""

from collections.abc import Sequence
from typing import Any

from qdrant_client import AsyncQdrantClient, models

from insightflow.core.config import Settings
from insightflow.core.exceptions import StorageError
from insightflow.rag.config import DistanceMetric, EmbeddingConfig
from insightflow.rag.models import Chunk, NormalizedDocument, RetrievedChunk

_DISTANCES: dict[DistanceMetric, models.Distance] = {
    "cosine": models.Distance.COSINE,
    "dot": models.Distance.DOT,
    "euclid": models.Distance.EUCLID,
    "manhattan": models.Distance.MANHATTAN,
}
_INDEXED_KEYWORD_FIELDS = (
    "document_id",
    "document_version",
    "index_fingerprint",
    "source_identifier",
    "mime_type",
)


def chunk_to_payload(
    document: NormalizedDocument,
    chunk: Chunk,
    *,
    index_fingerprint: str,
    document_chunk_count: int,
) -> dict[str, Any]:
    """Flatten one chunk and its source provenance into a Qdrant payload."""
    payload: dict[str, Any] = chunk.model_dump(mode="json")
    payload.update(
        source_identifier=document.source_identifier,
        source_name=document.source_name,
        mime_type=document.mime_type,
        document_title=document.title,
        parser_name=document.parser_name,
        parser_version=document.parser_version,
        index_fingerprint=index_fingerprint,
        document_chunk_count=document_chunk_count,
    )
    return payload


def payload_to_chunk(payload: dict[str, Any]) -> Chunk:
    """Rebuild the domain chunk stored by `chunk_to_payload`."""
    return Chunk.model_validate(
        {name: payload[name] for name in Chunk.model_fields if name in payload}
    )


def _match(key: str, value: str) -> models.FieldCondition:
    return models.FieldCondition(key=key, match=models.MatchValue(value=value))


class QdrantStore:
    """Store and query vectors generated by an external embedding provider."""

    def __init__(self, settings: Settings, *, client: AsyncQdrantClient | None = None) -> None:
        self.collection_name = settings.qdrant_collection
        self.vector_name = settings.qdrant_vector_name
        self._upload_batch_size = settings.rag_upload_batch_size
        self._client = client or AsyncQdrantClient(
            url=settings.qdrant_url,
            api_key=settings.qdrant_api_key or None,
        )

    async def is_available(self) -> bool:
        """Return whether Qdrant accepts a basic metadata request."""
        try:
            await self._client.get_collections()
        except Exception:
            return False
        return True

    async def ensure_collection(self, embedding: EmbeddingConfig) -> None:
        """Create the collection, or verify that its vectors match the embedding model."""
        distance = _DISTANCES[embedding.distance]
        try:
            exists = await self._client.collection_exists(self.collection_name)
            if exists:
                info = await self._client.get_collection(self.collection_name)
            else:
                await self._client.create_collection(
                    collection_name=self.collection_name,
                    vectors_config={
                        self.vector_name: models.VectorParams(
                            size=embedding.dimensions, distance=distance
                        )
                    },
                )
                for field_name in _INDEXED_KEYWORD_FIELDS:
                    await self._client.create_payload_index(
                        collection_name=self.collection_name,
                        field_name=field_name,
                        field_schema=models.PayloadSchemaType.KEYWORD,
                    )
                return
        except Exception as exc:
            raise StorageError("Qdrant collection setup failed") from exc

        vectors = info.config.params.vectors
        params = vectors.get(self.vector_name) if isinstance(vectors, dict) else None
        if params is None or params.size != embedding.dimensions or params.distance != distance:
            raise StorageError(
                "The Qdrant collection vectors do not match the configured embedding model"
            )

    async def has_document_version(
        self,
        document_id: str,
        document_version: str,
        index_fingerprint: str,
    ) -> bool:
        """Return whether every chunk of this document version is already stored."""
        version_filter = models.Filter(
            must=[
                _match("document_id", document_id),
                _match("document_version", document_version),
                _match("index_fingerprint", index_fingerprint),
            ]
        )
        try:
            points, _ = await self._client.scroll(
                collection_name=self.collection_name,
                scroll_filter=version_filter,
                limit=1,
                with_payload=["document_chunk_count"],
            )
            if not points or points[0].payload is None:
                return False
            counted = await self._client.count(
                collection_name=self.collection_name,
                count_filter=version_filter,
                exact=True,
            )
        except Exception as exc:
            raise StorageError("Qdrant document lookup failed") from exc
        return bool(counted.count == points[0].payload.get("document_chunk_count"))

    async def replace_document(
        self,
        document: NormalizedDocument,
        chunks: Sequence[Chunk],
        vectors: Sequence[Sequence[float]],
        index_fingerprint: str,
    ) -> None:
        """Delete every other point of the document, then write the new chunks."""
        if len(chunks) != len(vectors):
            raise ValueError("chunks and vectors must have equal lengths")
        points = [
            models.PointStruct(
                id=chunk.chunk_id,
                vector={self.vector_name: list(vector)},
                payload=chunk_to_payload(
                    document,
                    chunk,
                    index_fingerprint=index_fingerprint,
                    document_chunk_count=len(chunks),
                ),
            )
            for chunk, vector in zip(chunks, vectors, strict=True)
        ]
        # Deleting first means an interrupted write leaves an incomplete version, which
        # `has_document_version` reports as missing, so the next run rewrites it.
        stale_filter = models.Filter(
            must=[_match("document_id", document.document_id)],
            must_not=[models.HasIdCondition(has_id=[chunk.chunk_id for chunk in chunks])],
        )
        try:
            await self._client.delete(
                collection_name=self.collection_name,
                points_selector=models.FilterSelector(filter=stale_filter),
                wait=True,
            )
            for start in range(0, len(points), self._upload_batch_size):
                await self._client.upsert(
                    collection_name=self.collection_name,
                    points=points[start : start + self._upload_batch_size],
                    wait=True,
                )
        except Exception as exc:
            raise StorageError("Qdrant document write failed") from exc

    async def search_chunks(
        self,
        vector: Sequence[float],
        *,
        limit: int,
        document_ids: Sequence[str] | None = None,
        mime_types: Sequence[str] | None = None,
        score_threshold: float | None = None,
    ) -> list[RetrievedChunk]:
        """Return the closest stored chunks, ranked from 1, with their source identity."""
        conditions: list[models.Condition] = [
            models.FieldCondition(key=key, match=models.MatchAny(any=list(values)))
            for key, values in (("document_id", document_ids), ("mime_type", mime_types))
            if values
        ]
        try:
            result = await self._client.query_points(
                collection_name=self.collection_name,
                query=list(vector),
                using=self.vector_name,
                query_filter=models.Filter(must=conditions) if conditions else None,
                limit=limit,
                score_threshold=score_threshold,
                with_payload=True,
            )
        except Exception as exc:
            raise StorageError("Qdrant search failed") from exc
        return [
            RetrievedChunk(
                chunk=payload_to_chunk(point.payload or {}),
                source_identifier=(point.payload or {})["source_identifier"],
                source_name=(point.payload or {})["source_name"],
                score=point.score,
                rank=rank,
            )
            for rank, point in enumerate(result.points, start=1)
        ]

    async def close(self) -> None:
        """Release client network resources."""
        await self._client.close()
